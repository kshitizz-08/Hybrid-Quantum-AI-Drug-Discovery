"""
FastAPI application entry point.

Hybrid Quantum-AI Drug Discovery Platform — Backend API
"""
import sys
from pathlib import Path

# Ensure project root directory is in sys.path to resolve 'ml' module
PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

import logging
from contextlib import asynccontextmanager

from fastapi import FastAPI, Request
from fastapi.middleware.cors import CORSMiddleware
from fastapi.responses import JSONResponse

from app.config import get_settings
from app.database import init_db, SessionLocal

# Configure logging
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
)
logger = logging.getLogger(__name__)
settings = get_settings()


# ── Application Lifecycle ─────────────────────────────────────

@asynccontextmanager
async def lifespan(app: FastAPI):
    """Startup and shutdown events."""
    logger.info("Starting %s v%s", settings.app_name, settings.app_version)
    logger.info("Database: %s", settings.database_url.split("://")[0])

    # Create all database tables on startup
    init_db()
    logger.info("Database initialized successfully.")

    # Seed default data (idempotent — safe to run every startup)
    from app.services.target_service import seed_egfr_target
    db = SessionLocal()
    try:
        seed_egfr_target(db)
    finally:
        db.close()

    yield

    logger.info("Shutting down %s", settings.app_name)


# ── FastAPI App ───────────────────────────────────────────────

app = FastAPI(
    title=settings.app_name,
    version=settings.app_version,
    description=(
        "A computational drug discovery research platform combining AI prediction, "
        "quantum optimization, and molecular docking for candidate prioritization.\n\n"
        "**Scientific Disclaimer**: Results generated by this platform are computational "
        "predictions and prioritization results. They do not constitute clinical validation, "
        "medical advice, or proof of drug efficacy or safety."
    ),
    docs_url="/docs",
    redoc_url="/redoc",
    openapi_url="/openapi.json",
    lifespan=lifespan,
)


# ── CORS Middleware ───────────────────────────────────────────

app.add_middleware(
    CORSMiddleware,
    allow_origins=settings.cors_origins,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)


# ── Global Exception Handler ──────────────────────────────────

@app.exception_handler(Exception)
async def global_exception_handler(request: Request, exc: Exception):
    """
    Catch-all exception handler.
    Never expose raw tracebacks to the client.
    """
    logger.exception("Unhandled exception on %s %s", request.method, request.url)
    return JSONResponse(
        status_code=500,
        content={
            "error": "internal_server_error",
            "message": "An unexpected error occurred. Please try again or contact support.",
        },
    )


